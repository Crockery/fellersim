use std::{fs, path::Path};

use fellersim_core::preparation::*;
use fellersim_core::{
    AbilityDamageResult, ActionPriorityListV2, AplBooleanReference, AplBuff, AplComparisonOperator,
    AplExpression, AplExpressionNode, AplNumericOperand, AplNumericReference, AplResource,
    AplResourceMeasure, AplRule, AplTargetEffectKind, AplTargetEffectModel,
    AplTargetEffectProperty, AplTargetEffectSource, ChannelModel, ConfidenceInterval, DotModel,
    DpsAbilityKind, DpsAbilityModel, DpsEvidenceClaimSnapshot, DpsEvidenceClaimStatus,
    DpsEvidenceScope, DpsEvidenceSnapshotV1, DpsGcdHasteMode, DpsTalentModel,
    DynamicMechanicHandler, DynamicMechanicInstance, MechanicClassification, NormalizedDpsProfile,
    ProcResult, ScenarioNoOpAbility, SimulationError, SimulationErrorCode, SimulationProgress,
    SimulationRequest, SimulationResult, StationaryDummyScenarioV3, TargetDamageResult,
    UptimeResult,
};
use ts_rs::TS;

fn push_decl<T: TS>(config: &ts_rs::Config, declarations: &mut Vec<String>) {
    declarations.push(
        format!("export {}", T::decl(config))
            .lines()
            .map(str::trim_end)
            .collect::<Vec<_>>()
            .join("\n"),
    );
}

fn main() {
    let config = ts_rs::Config::new().with_large_int("number");
    let mut declarations = Vec::new();
    push_decl::<CharacterBuild>(&config, &mut declarations);
    push_decl::<CharacterPosition>(&config, &mut declarations);
    push_decl::<CharacterItem>(&config, &mut declarations);
    push_decl::<CharacterModifier>(&config, &mut declarations);
    push_decl::<CharacterGem>(&config, &mut declarations);
    push_decl::<CharacterTraitTree>(&config, &mut declarations);
    push_decl::<CharacterTraitRoll>(&config, &mut declarations);
    push_decl::<CharacterBlessing>(&config, &mut declarations);
    push_decl::<SimulationOptions>(&config, &mut declarations);
    push_decl::<SimulationInput>(&config, &mut declarations);

    push_decl::<SimulationRequest>(&config, &mut declarations);
    push_decl::<StationaryDummyScenarioV3>(&config, &mut declarations);
    push_decl::<DpsEvidenceScope>(&config, &mut declarations);
    push_decl::<DpsEvidenceClaimStatus>(&config, &mut declarations);
    push_decl::<DpsEvidenceClaimSnapshot>(&config, &mut declarations);
    push_decl::<DpsEvidenceSnapshotV1>(&config, &mut declarations);
    push_decl::<ActionPriorityListV2>(&config, &mut declarations);
    push_decl::<AplRule>(&config, &mut declarations);
    push_decl::<AplExpressionNode>(&config, &mut declarations);
    push_decl::<AplExpression>(&config, &mut declarations);
    push_decl::<AplBooleanReference>(&config, &mut declarations);
    push_decl::<AplNumericOperand>(&config, &mut declarations);
    push_decl::<AplNumericReference>(&config, &mut declarations);
    push_decl::<AplComparisonOperator>(&config, &mut declarations);
    push_decl::<AplResource>(&config, &mut declarations);
    push_decl::<AplResourceMeasure>(&config, &mut declarations);
    push_decl::<AplBuff>(&config, &mut declarations);
    push_decl::<NormalizedDpsProfile>(&config, &mut declarations);
    push_decl::<AplTargetEffectModel>(&config, &mut declarations);
    push_decl::<AplTargetEffectSource>(&config, &mut declarations);
    push_decl::<AplTargetEffectKind>(&config, &mut declarations);
    push_decl::<AplTargetEffectProperty>(&config, &mut declarations);
    push_decl::<ScenarioNoOpAbility>(&config, &mut declarations);
    push_decl::<DpsAbilityKind>(&config, &mut declarations);
    push_decl::<DpsGcdHasteMode>(&config, &mut declarations);
    push_decl::<DpsAbilityModel>(&config, &mut declarations);
    push_decl::<ChannelModel>(&config, &mut declarations);
    push_decl::<DotModel>(&config, &mut declarations);
    push_decl::<DpsTalentModel>(&config, &mut declarations);
    push_decl::<MechanicClassification>(&config, &mut declarations);
    push_decl::<DynamicMechanicHandler>(&config, &mut declarations);
    push_decl::<DynamicMechanicInstance>(&config, &mut declarations);
    push_decl::<SimulationProgress>(&config, &mut declarations);
    push_decl::<SimulationResult>(&config, &mut declarations);
    push_decl::<ConfidenceInterval>(&config, &mut declarations);
    push_decl::<AbilityDamageResult>(&config, &mut declarations);
    push_decl::<ProcResult>(&config, &mut declarations);
    push_decl::<TargetDamageResult>(&config, &mut declarations);
    push_decl::<UptimeResult>(&config, &mut declarations);
    push_decl::<SimulationErrorCode>(&config, &mut declarations);
    push_decl::<SimulationError>(&config, &mut declarations);

    let output = format!(
        "// This file is generated by crates/fellersim. Do not edit manually.\n{}\n",
        declarations.join("\n\n")
    );
    let Some(destination) = std::env::args().nth(1) else {
        print!("{output}");
        return;
    };
    let path = Path::new(&destination);
    fs::create_dir_all(path.parent().expect("binding path must have a parent"))
        .expect("failed to create binding directory");
    fs::write(path, output).expect("failed to write simulator bindings");
    println!("Generated {}", path.display());
}
